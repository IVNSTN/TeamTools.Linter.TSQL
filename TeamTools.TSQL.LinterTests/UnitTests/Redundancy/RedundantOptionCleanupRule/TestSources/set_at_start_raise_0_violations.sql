CREATE PROCEDURE dbo.SetXactAbortOffAtEnd
AS
BEGIN
    SET NOCOUNT, XACT_ABORT ON;

    SET TRANSACTION ISOLATION LEVEL REPEATABLE READ;

    CREATE TABLE #TempData (Id INT);
    INSERT INTO #TempData (Id) VALUES (1);
END;
GO

